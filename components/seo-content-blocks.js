export function SeoContentBlock({ page }) {
  const content = seoPages[page];

  if (!content) {
    return null;
  }

  return (
    <section className="seo-content-section" aria-labelledby={`${page}-seo-title`}>
      <div className="container">
        <p className="seo-eyebrow">{content.eyebrow}</p>
        <h2 id={`${page}-seo-title`}>{content.title}</h2>
        <p className="seo-intro">{content.intro}</p>
        <div className="seo-content-grid">
          {content.sections.map((section) => (
            <article className="seo-content-item" key={section.title}>
              <h3>{section.title}</h3>
              <p>{section.body}</p>
            </article>
          ))}
        </div>
        <div className="seo-faq-block">
          <h3>Frequently Asked Questions</h3>
          {content.faqs.map(([question, answer]) => (
            <details key={question}>
              <summary>{question}</summary>
              <p>{answer}</p>
            </details>
          ))}
        </div>
      </div>
    </section>
  );
}

function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

export function getSeoContentHtml(page) {
  const content = seoPages[page];

  if (!content) {
    return "";
  }

  const sectionItems = content.sections
    .map(
      (section) => `
        <article class="seo-content-item">
          <h3>${escapeHtml(section.title)}</h3>
          <p>${escapeHtml(section.body)}</p>
        </article>`
    )
    .join("");

  const faqItems = content.faqs
    .map(
      ([question, answer]) => `
        <details>
          <summary>${escapeHtml(question)}</summary>
          <p>${escapeHtml(answer)}</p>
        </details>`
    )
    .join("");

  return `
    <section class="seo-content-section" aria-labelledby="${escapeHtml(page)}-seo-title">
      <div class="container">
        <p class="seo-eyebrow">${escapeHtml(content.eyebrow)}</p>
        <h2 id="${escapeHtml(page)}-seo-title">${escapeHtml(content.title)}</h2>
        <p class="seo-intro">${escapeHtml(content.intro)}</p>
        <div class="seo-content-grid">${sectionItems}</div>
        <div class="seo-faq-block">
          <h3>Frequently Asked Questions</h3>
          ${faqItems}
        </div>
      </div>
    </section>`;
}

export function insertSeoContentBeforeFooter(html, page) {
  const footerMarker = '<footer id="tw-footer"';
  const index = html.indexOf(footerMarker);

  if (index === -1) {
    return `${html}${getSeoContentHtml(page)}`;
  }

  return `${html.slice(0, index)}${getSeoContentHtml(page)}${html.slice(index)}`;
}
